"""Generate voiceover lines with Kokoro (open-source neural TTS, Apache-2.0) and write src/vo/timings.ts.
Usage: <venv-python> make-voice.py <dir-with-kokoro-v1.0.onnx-and-voices-v1.0.bin>
Real recordings can replace any public/vo/<video>/NN.wav afterwards; rerun with --keep to only re-time."""
import json, sys, subprocess, os, numpy as np, soundfile as sf
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
scripts=json.load(open(os.path.join(ROOT,'scripts','scripts.json')))
keep='--keep' in sys.argv
if not keep:
    from kokoro_onnx import Kokoro
    k=Kokoro(os.path.join(sys.argv[1],'kokoro-v1.0.onnx'),os.path.join(sys.argv[1],'voices-v1.0.bin'))
FPS=30; out={}
for vid,s in scripts.items():
    d=os.path.join(ROOT,'public','vo',vid); os.makedirs(d,exist_ok=True)
    t=0.3; lines=[]
    for i,text in enumerate(s['lines'],1):
        p=os.path.join(d,f'{i:02d}.wav')
        if not keep:
            a,sr=k.create(text,voice=s['voice'],speed=s['speed'],lang=s['lang'])
            raw=p+'.raw.wav'; sf.write(raw,a,sr)
            # trim silence, warm EQ, normalise loudness, 44.1k mono
            subprocess.run(['ffmpeg','-y','-loglevel','error','-i',raw,'-af',
              'silenceremove=start_periods=1:start_threshold=-45dB,areverse,silenceremove=start_periods=1:start_threshold=-45dB,areverse,'
              'highpass=f=70,equalizer=f=180:t=q:w=1:g=2,equalizer=f=4500:t=q:w=1.5:g=1.5,loudnorm=I=-16:TP=-1.5:LRA=7,aresample=44100',
              '-ac','1',p],check=True); os.remove(raw)
        dur=float(subprocess.run(['ffprobe','-v','error','-show_entries','format=duration','-of','csv=p=0',p],capture_output=True,text=True).stdout)
        lines.append({'text':text,'file':f'vo/{vid}/{i:02d}.wav','start':round(t,3),'dur':round(dur,3)})
        t+=dur+(0.45 if i==1 else 0.3)
    out[vid]={'title':s['title'],'lines':lines,'total':round(t-0.3+3.0,2)}
    print(vid,'total',out[vid]['total'],'s')
os.makedirs(os.path.join(ROOT,'src','vo'),exist_ok=True)
with open(os.path.join(ROOT,'src','vo','timings.ts'),'w') as f:
    f.write('// Generated by scripts/make-voice.py. Do not edit by hand.\n')
    f.write('export type VoLine = { text: string; file: string; start: number; dur: number };\n')
    f.write('export const TIMINGS: Record<string, { title: string; total: number; lines: VoLine[] }> = '+json.dumps(out,indent=1)+';\n')
