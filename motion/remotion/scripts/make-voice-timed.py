"""Generate voice lines with word-level timings (Kokoro model-files-v1.1, which reports phoneme durations).
Usage: <venv-python> -I scripts/make-voice-timed.py <dir with v1.1 kokoro-v1.0.onnx + voices-v1.0.bin> --only=id,id
Writes public/vo/<id>/NN.wav and merges lines (with `words`: [{w,s,e}] relative to the line) into src/vo/timings.ts."""
import json, os, sys, subprocess
import numpy as np, soundfile as sf
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
from kokoro_onnx import Kokoro
model_dir = sys.argv[1]
only = [a.split('=', 1)[1] for a in sys.argv if a.startswith('--only=')][0].split(',')
k = Kokoro(os.path.join(model_dir, 'kokoro-v1.0.onnx'), os.path.join(model_dir, 'voices-v1.0.bin'))
scripts = json.load(open(os.path.join(ROOT, 'scripts', 'scripts.json')))
ts = open(os.path.join(ROOT, 'src', 'vo', 'timings.ts')).read()
out = json.loads(ts[ts.index('> = ') + 4:ts.rindex(';')])

def words_from(timings, text, lang):
    """Map each script word onto the timed phoneme stream.
    Each word is phonemized on its own; its share of the phoneme stream gives its exact span,
    which stays correct even when the phonemizer merges words."""
    stream = [t for t in timings if t.phoneme.strip() and any(c.isalpha() or c in 'ˈˌːɐɑɒæəɜɪʊʌɔɛɡŋθðʃʒʧʤɹɾʔ' for c in t.phoneme)]
    tw = text.split()
    lens = []
    for w in tw:
        ph = k.tokenizer.phonemize(w.replace('HAMLET', 'Hamlet'), lang)
        lens.append(max(1, len([c for c in ph if c.strip() and c not in ".,?!;:'\"-"])))
    total = sum(lens); n = len(stream); res = []; acc = 0
    for w, L in zip(tw, lens):
        i0 = min(n - 1, int(round(acc * n / total))); acc += L
        i1 = min(n - 1, max(i0, int(round(acc * n / total)) - 1))
        res.append((w, stream[i0].start, stream[i1].end))
    return res

for vid in only:
    s = scripts[vid]
    d = os.path.join(ROOT, 'public', 'vo', vid); os.makedirs(d, exist_ok=True)
    t = 0.3; lines = []
    for i, text in enumerate(s['lines'], 1):
        spoken = text.replace('HAMLET', 'Hamlet')
        audio, sr, tim = k.create_timed(spoken, voice=s['voice'], speed=s['speed'], lang=s['lang'])
        words = words_from(tim, text, s['lang'])
        a0 = max(0.0, words[0][1] - 0.06); a1 = min(len(audio) / sr, words[-1][2] + 0.18)
        clip = audio[int(a0 * sr):int(a1 * sr)]
        raw = os.path.join(d, f'{i:02d}.raw.wav'); sf.write(raw, clip, sr)
        p = os.path.join(d, f'{i:02d}.wav')
        subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', raw, '-af',
            'highpass=f=85,deesser=i=0.35,acompressor=threshold=-21dB:ratio=3.2:attack=6:release=90:makeup=2,'
            'equalizer=f=220:t=q:w=1:g=1.5,equalizer=f=3200:t=q:w=1.3:g=2.2,equalizer=f=9000:t=h:w=1:g=1.2,'
            'aecho=0.85:0.5:23|41:0.07|0.05,loudnorm=I=-16:TP=-1.5:LRA=6', '-ar', '44100', '-ac', '1', p], check=True)
        os.remove(raw)
        dur = a1 - a0
        lines.append({'text': text, 'file': f'vo/{vid}/{i:02d}.wav', 'start': round(t, 3), 'dur': round(dur, 3),
                      'words': [{'w': w, 's': round(ws - a0, 3), 'e': round(we - a0, 3)} for w, ws, we in words]})
        t += dur + (0.45 if i == 1 else 0.3)
    out[vid] = {'title': s['title'], 'lines': lines, 'total': round(t - 0.3 + 3.0, 2)}
    print(vid, 'total', out[vid]['total'])
with open(os.path.join(ROOT, 'src', 'vo', 'timings.ts'), 'w') as f:
    f.write('// Generated by scripts/make-voice.py and scripts/make-voice-timed.py. Do not edit by hand.\n')
    f.write('export type VoWord = { w: string; s: number; e: number };\n')
    f.write('export type VoLine = { text: string; file: string; start: number; dur: number; words?: VoWord[] };\n')
    f.write('export const TIMINGS: Record<string, { title: string; total: number; lines: VoLine[] }> = ' + json.dumps(out, indent=1) + ';\n')
