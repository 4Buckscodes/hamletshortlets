"""Extract Newsreader glyph outlines (as SVG path data) for the 3D text. Needs fonttools + brotli."""
import sys, json
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
f=TTFont('public/fonts/newsreader-latin-wght.woff2')
f=instantiateVariableFont(f,{'wght':620,'opsz':72} if 'opsz' in [a.axisTag for a in f['fvar'].axes] else {'wght':620})
gs=f.getGlyphSet(); cmap=f.getBestCmap(); upm=f['head'].unitsPerEm
out={}
for ch in "0123456789%?₦":
    if ord(ch) not in cmap: print('missing',ch); continue
    g=cmap[ord(ch)]; pen=SVGPathPen(gs); gs[g].draw(pen)
    out[ch]={'d':pen.getCommands(),'adv':gs[g].width/upm}
open('src/three/glyphs.ts','w').write('// Newsreader (wght 620) outlines, units per em = %d. Generated by scripts/make-glyphs.py.\nexport const UPM = %d;\nexport const GLYPHS: Record<string, { d: string; adv: number }> = %s;\n'%(upm,upm,json.dumps(out)))
print('ok',list(out),upm)
